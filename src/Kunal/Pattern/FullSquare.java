package Kunal.Pattern;

public class FullSquare {
    static public void printFullSquare(int n) {
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= n; j++) {
                System.out.print("* ");
            }
            System.out.println();
        }
    }

    public static void main(String[] args) {
        int n = 5;
        printFullSquare(n);
    }
}
